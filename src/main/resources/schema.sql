-- Address Book table
CREATE TABLE ADDRESS_BOOK (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CREATED_DATE TIMESTAMP,
    UPDATED_DATE TIMESTAMP,
    BRANCH_MANAGER VARCHAR(255),
    TYPE VARCHAR(50)
);

-- Contact table
CREATE TABLE CONTACT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CREATED_DATE TIMESTAMP,
    UPDATED_DATE TIMESTAMP,
    NAME VARCHAR(255),
    PHONE_NUMBER VARCHAR(20)
);

-- Index on Contact ID
CREATE INDEX IDX_CONTACT_ID ON CONTACT(ID);

-- Join table for many-to-many relationship
CREATE TABLE ADDRESSBOOK_CONTACT (
    ADDRESSBOOK_ID BIGINT NOT NULL,
    CONTACT_ID BIGINT NOT NULL,
    PRIMARY KEY (ADDRESSBOOK_ID, CONTACT_ID),
    FOREIGN KEY (ADDRESSBOOK_ID) REFERENCES ADDRESS_BOOK(ID),
    FOREIGN KEY (CONTACT_ID) REFERENCES CONTACT(ID)
);
